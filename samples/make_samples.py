def build_docx(
    path: Path,
    blocks: list[tuple[str, str]],
    table: list[tuple[str, ...]] | None = None,
    after: list[tuple[str, str]] | None = None,
) -> None:
    d = docx.Document()

    def add(items: list[tuple[str, str]]) -> None:
        for kind, text in items:
            if kind == "h":
                d.add_heading(text, 1)
            else:
                d.add_paragraph(text)

    add(blocks)
    if table:
        t = d.add_table(rows=len(table), cols=len(table[0]))
        t.style = "Table Grid"
        for r, row in enumerate(table):
            for c, val in enumerate(row):
                t.cell(r, c).text = val
    if after:
        add(after)
    d.save(str(path))


def docx_to_doc(src: Path, dst: Path) -> bool:
    if shutil.which("docker") is None:
        print("docker не найден — DOC не создан")
        return False
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        shutil.copy(src, work / "in.docx")
        cmd = [
            "docker",
            "run",
            "--rm",
            "--network",
            "none",
            "-v",
            f"{work}:/work",
            "--entrypoint",
            "soffice",
            CONVERTER_IMAGE,
            "--headless",
            "--convert-to",
            "doc:MS Word 97",
            "--outdir",
            "/work",
            "/work/in.docx",
        ]
        # Аргументы — константы и временный каталог, пользовательского ввода нет.
        env = {**os.environ, "MSYS_NO_PATHCONV": "1"}
        result = subprocess.run(cmd, check=False, capture_output=True, text=True, env=env)  # noqa: S603
        out = work / "in.doc"
        if result.returncode != 0 or not out.exists():
            print("конвертация в DOC не удалась:", result.stderr.strip()[:300])
            return False
        shutil.copy(out, dst)
    return True


