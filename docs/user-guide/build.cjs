// «**жирный**» внутри строки
function runs(text, opts = {}) {
  return text.split(/(\*\*[^*]+\*\*)/).filter(Boolean).map((part) =>
    part.startsWith('**')
      ? new TextRun({ text: part.slice(2, -2), bold: true, ...opts })
      : new TextRun({ text: part, ...opts }),
  )
}
const p = (text, opts = {}) => new Paragraph({ children: runs(text), spacing: { after: 120 }, ...opts })
const h1 = (text) => new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(text)], pageBreakBefore: true })
const h2 = (text) => new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(text)] })
const h3 = (text) => new Paragraph({ heading: HeadingLevel.HEADING_3, children: [new TextRun(text)] })
const bullets = (items) =>
  items.map((t) => new Paragraph({ children: runs(t), numbering: { reference: 'bullets', level: 0 }, spacing: { after: 60 } }))
function steps(items) {
  stepsInstance += 1
  return items.map(
    (t) => new Paragraph({ children: runs(t), numbering: { reference: 'steps', level: 0, instance: stepsInstance }, spacing: { after: 60 } }),
  )
}
function note(text, kind = 'info') {
  const colors = { info: ['EFF6FF', '93C5FD'], warn: ['FFFBEB', 'F59E0B'], danger: ['FEF2F2', 'F87171'] }[kind]
  return new Paragraph({
    children: runs(text),
    shading: { type: ShadingType.CLEAR, fill: colors[0], color: 'auto' },
    border: { left: { style: BorderStyle.SINGLE, size: 18, color: colors[1], space: 8 } },
    spacing: { before: 120, after: 160 },
    indent: { left: 120, right: 120 },
  })
}
function pngSize(file) {
  const b = fs.readFileSync(file)
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20), data: b }
}
function image(name, caption, maxWidth = IMAGE_WIDTH) {
  const { w, h, data } = pngSize(path.join(SHOTS, `${name}.png`))
  const width = Math.min(maxWidth, Math.round(w / SHOT_SCALE), Math.round((IMAGE_MAX_HEIGHT * w) / h))
  figure += 1
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 120, after: 60 },
      keepNext: true,
      children: [new ImageRun({ type: 'png', data, transformation: { width, height: Math.round((width * h) / w) } })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 200 },
      children: [new TextRun({ text: `Рисунок ${figure}. ${caption}`, italics: true, size: 20, color: '475569' })],
    }),
  ]
}
const border = { style: BorderStyle.SINGLE, size: 4, color: 'CBD5E1' }
const borders = { top: border, bottom: border, left: border, right: border }
// headers = null — таблица без строки заголовков
function table(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0)
  const scaled = widths.map((w) => Math.round((w * TEXT_WIDTH) / total))
  scaled[scaled.length - 1] += TEXT_WIDTH - scaled.reduce((a, b) => a + b, 0)
  const cell = (text, i, head) =>
    new TableCell({
      borders,
      width: { size: scaled[i], type: WidthType.DXA },
      shading: head ? { type: ShadingType.CLEAR, fill: 'E2E8F0', color: 'auto' } : undefined,
      margins: { top: 60, bottom: 60, left: 100, right: 100 },
      children: [new Paragraph({ children: runs(text, { size: 22, bold: head || undefined }) })],
    })
  return new Table({
    width: { size: TEXT_WIDTH, type: WidthType.DXA },
    columnWidths: scaled,
    rows: [
      ...(headers ? [new TableRow({ tableHeader: true, children: headers.map((t, i) => cell(t, i, true)) })] : []),
      ...rows.map((r) => new TableRow({ cantSplit: true, children: r.map((t, i) => cell(t, i, false)) })),
    ],
  })
}
